/*
 * Сквозной счётчик для id, которые должны быть уникальны в пределах
 * страницы, — вместо crypto.randomUUID(): со случайными id HTML менялся
 * при каждой сборке, засоряя диффы и без нужды инвалидируя кеш страниц.
 *
 * Детерминированность держится на том, что Astro рендерит страницы
 * последовательно (build.concurrency по умолчанию 1) в стабильном порядке.
 * Если сборку когда-нибудь распараллелят, id останутся уникальными,
 * но перестанут совпадать от сборки к сборке.
 */

let counter = 0;

export function nextUid(): number {
  return ++counter;
}
